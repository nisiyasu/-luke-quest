import fs from 'node:fs/promises';
import path from 'node:path';
import { build } from 'esbuild';

const root = process.cwd();
const sourceDir = path.join(root, 'prototypes', 'modern-3d');
const sourceHtml = path.join(sourceDir, 'index.html');
const distDir = path.join(root, 'dist');
const distHtml = path.join(distDir, 'luke-quest-modern-3d.html');
const distReadme = path.join(distDir, 'README.md');

const html = await fs.readFile(sourceHtml, 'utf8');
const moduleMatch = html.match(/<script\s+type=["']module["']>([\s\S]*?)<\/script>/i);
if (!moduleMatch) throw new Error('source module script not found');

const result = await build({
  stdin: {
    contents: moduleMatch[1],
    resolveDir: sourceDir,
    sourcefile: 'index-inline-entry.js',
    loader: 'js'
  },
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'browser',
  target: ['es2020'],
  external: ['three'],
  legalComments: 'none',
  minify: false
});

if (result.outputFiles.length !== 1) throw new Error(`unexpected bundle outputs: ${result.outputFiles.length}`);
const bundledJs = result.outputFiles[0].text;
let packaged = html.replace(moduleMatch[0], `<script type="module">\n${bundledJs}\n</script>`);
packaged = packaged.replace(
  '<title>LUKE QUEST Modern 3D — M03 Composition Rebuild v61</title>',
  '<title>LUKE QUEST Modern 3D — Single HTML Distribution</title>\n<meta name="lq-distribution" content="m10-p02-single-html">'
);

const localModuleResidue = [
  './assets.js',
  './natural-assets.js',
  './m04-target-assets.js',
  './m04-conifer-target-v31.js',
  './m04-bank-target-v4.js',
  './m04-water-target-v3.js'
].filter(token => packaged.includes(token));
if (localModuleResidue.length) throw new Error(`local module residue: ${localModuleResidue.join(', ')}`);
if (!packaged.includes('https://cdn.jsdelivr.net/npm/three@0.186.0/build/three.module.js')) {
  throw new Error('Three.js CDN authority missing from package');
}

await fs.mkdir(distDir, { recursive: true });
await fs.writeFile(distHtml, packaged, 'utf8');
await fs.writeFile(distReadme, `# LUKE QUEST Modern 3D single-HTML distribution\n\nGenerated by \`.ci/build-m10-p02-single-html.mjs\` from \`prototypes/modern-3d/index.html\`.\n\n## Distribution\n\n- \`dist/luke-quest-modern-3d.html\` contains the source HTML/CSS and all repository-local JavaScript modules bundled into one HTML file.\n- The development source under \`prototypes/modern-3d/\` remains the editable source of truth.\n\n## External dependency\n\nThe packaged file intentionally keeps the canonical Three.js ESM CDN dependency:\n\n- \`https://cdn.jsdelivr.net/npm/three@0.186.0/build/three.module.js\`\n\nTherefore the distribution is single-HTML with respect to repository-local HTML/CSS/JS, but it is **not offline/self-contained**. Network access to jsDelivr is required.\n\n## Start condition\n\nServe over HTTP(S); do not rely on \`file://\`. Example from repository root:\n\n\`python3 -m http.server 8142\`\n\nThen open:\n\n- HQ: \`http://127.0.0.1:8142/dist/luke-quest-modern-3d.html?quality=high&m10dpr=3\`\n- iPhone-practical profile: \`http://127.0.0.1:8142/dist/luke-quest-modern-3d.html?quality=practical&m10dpr=3\`\n\nPhysical iPhone verification is not implied by CI/browser execution.\n\nIOS_PHYSICAL_VERIFICATION: PENDING\n`, 'utf8');

console.log(`wrote ${path.relative(root, distHtml)}`);
console.log(`bytes ${Buffer.byteLength(packaged, 'utf8')}`);
